//! Top-level project configuration.
//!
//! A project defines the output settings, audio source, and all clips
//! that make up a video. Projects are serialized as JSON and loaded by
//! the editor or headless renderer.

pub mod loader;

use crate::clip::ClipDef;

/// Video encoding configuration for the output file.
///
/// Controls H.264 encoding quality and compatibility settings.
/// All fields have sensible defaults; omitting the `encoding` key
/// in the project JSON produces the defaults.
#[derive(Debug, Clone, serde::Deserialize, serde::Serialize)]
pub struct EncodingConfig {
    /// Constant Rate Factor (quality). Lower = better quality, larger file.
    /// Range: 0–51. Default: 18 (visually lossless).
    #[serde(default = "default_crf")]
    pub crf: u32,
    /// Encoding preset. One of: ultrafast, superfast, veryfast, faster,
    /// fast, medium, slow, slower, veryslow. Default: "medium".
    #[serde(default = "default_preset")]
    pub preset: String,
    /// Output pixel format. Default: "yuv420p" (maximum compatibility).
    #[serde(default = "default_pixel_format")]
    pub pixel_format: String,
}

fn default_crf() -> u32 {
    18
}

fn default_preset() -> String {
    "medium".into()
}

fn default_pixel_format() -> String {
    "yuv420p".into()
}

impl Default for EncodingConfig {
    fn default() -> Self {
        Self {
            crf: default_crf(),
            preset: default_preset(),
            pixel_format: default_pixel_format(),
        }
    }
}

/// Top-level project configuration.
///
/// Deserialized from a JSON file generated by an agent or hand-authored.
/// Paths within the project are resolved relative to the project file's
/// parent directory.
#[derive(Debug, Clone, serde::Deserialize, serde::Serialize)]
pub struct Project {
    /// Output resolution [width, height] in pixels.
    pub resolution: [u32; 2],
    /// Output frames per second.
    pub fps: u32,
    /// Total duration in seconds.
    pub duration: f64,
    /// Output file path.
    pub output: String,
    /// Background color as [R, G, B, A], default #2c2e34 (opaque dark gray).
    #[serde(default = "default_background")]
    pub background: [u8; 4],
    /// Audio configuration, if any.
    pub audio: Option<AudioConfig>,
    /// Encoding settings for the output video.
    #[serde(default)]
    pub encoding: EncodingConfig,
    /// All clips in the project.
    pub clips: Vec<ClipDef>,
}

fn default_background() -> [u8; 4] {
    [0x2c, 0x2e, 0x34, 0xff]
}

/// Audio source configuration.
#[derive(Debug, Clone, serde::Deserialize, serde::Serialize)]
pub struct AudioConfig {
    /// Path to the audio file, relative to the project file.
    pub path: String,
    /// Start time offset in seconds.
    pub start_time: f64,
}
